import assert from "node:assert/strict";
import { createMemoryCollections } from "../services/memoryDatabase";
import { ObjectId } from "mongodb";
import { adminAccount, sendAdminUserMessage } from "../services/adminUserMessaging";
async function main() {
 const collections = createMemoryCollections();
 const sender = { uid: "admin-1", displayName: "Admin" };
 const recipient = { uid: "user-1", displayName: "User" };
 let notifications = 0;
 const notify = async (input: any) => { assert.equal(input.userId, recipient.uid); notifications++; };
 const result = await sendAdminUserMessage(collections, sender, recipient, "Hello", "request-123456789", notify);
 const conversation = await collections.conversationCollection.findOne({ _id: new ObjectId(result.conversationId) });
 assert.deepEqual(conversation?.participants, [sender.uid, recipient.uid]);
 assert.equal(conversation?.lastMessage, "Hello");
 assert.deepEqual(conversation?.unreadBy, [recipient.uid]);
 await collections.conversationCollection.updateOne({ _id: conversation?._id }, { $set: { unreadBy: [] } });
 const retry = await sendAdminUserMessage(collections, sender, recipient, "Hello", "request-123456789", notify);
 assert.equal(retry.alreadySent, true);
 assert.equal(await collections.messageCollection.countDocuments({}), 1);
 assert.equal(notifications, 1);
 assert.deepEqual((await collections.conversationCollection.findOne({ _id: conversation?._id }))?.unreadBy, []);
 await assert.rejects(sendAdminUserMessage(collections, sender, recipient, "Changed", "request-123456789", notify));
 await assert.rejects(sendAdminUserMessage(collections, sender, sender, "Hi", "request-123456789", notify));
 await assert.rejects(sendAdminUserMessage(collections, sender, { uid: "" }, "Hi", "request-123456789", notify));
 await assert.rejects(sendAdminUserMessage(collections, sender, recipient, "x".repeat(1001), "request-123456789", notify));
 await sendAdminUserMessage(collections, sender, recipient, "Second message", "request-987654321", notify);
 assert.equal(await collections.conversationCollection.countDocuments({}), 1);
 const other = { uid: "user-2", displayName: "Other user" };
 const otherResult = await sendAdminUserMessage(collections, sender, other, "Announcement", "request-123456789", async input => { assert.equal(input.userId, other.uid); });
 assert.notEqual(otherResult.conversationId, result.conversationId);
 assert.equal(await collections.conversationCollection.countDocuments({}), 2);
 assert.equal(await collections.messageCollection.countDocuments({ conversationId: otherResult.conversationId }), 1);
 const legacy = { buyerId: "user-3", sellerId: sender.uid, participants: ["user-3", sender.uid], productId: "existing-product", createdAt: new Date(), updatedAt: new Date() };
 const legacyResult = await collections.conversationCollection.insertOne(legacy);
 const reused = await sendAdminUserMessage(collections, sender, { uid: "user-3" }, "Support reply", "request-123456789", async () => {});
 assert.equal(reused.conversationId, legacyResult.insertedId.toString());
 assert.equal((await collections.messageCollection.findOne({ conversationId: reused.conversationId }))?.productId, "existing-product");
 const safe = adminAccount({ _id: new ObjectId(), uid: "user", accessToken: "secret", session: "secret", password: "secret", email: "user@example.com" });
 assert.equal(safe.email, "user@example.com"); assert.equal(safe.accessToken, undefined); assert.equal(safe.password, undefined); assert.equal(safe.session, undefined);
 console.log("Admin message delivery, reply participants, retries, account validation and secret exclusion passed.");
}
void main().catch(error => { console.error(error); process.exitCode = 1; });
